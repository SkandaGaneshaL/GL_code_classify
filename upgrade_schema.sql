-- Run this once if AG_GL_ACCOUNT_HISTORY_CASES was created from the first POC schema.
-- These columns preserve the additional fields in gl_account_history_poc_120.xlsx.

ALTER TABLE AG_GL_ACCOUNT_HISTORY_CASES ADD (
    INVOICE_ID VARCHAR2(200 CHAR),
    INVOICE_DISTRIBUTION_ID VARCHAR2(200 CHAR),
    DIST_CODE_COMBINATION_ID VARCHAR2(200 CHAR),
    VENDOR_ID VARCHAR2(200 CHAR),
    VENDOR_SITE_ID VARCHAR2(200 CHAR),
    BUSINESS_UNIT_ID VARCHAR2(200 CHAR),
    LEDGER_ID VARCHAR2(200 CHAR),
    CHART_OF_ACCOUNTS_ID VARCHAR2(200 CHAR),
    DATASET_TYPE VARCHAR2(100 CHAR),
    IS_SYNTHETIC VARCHAR2(20 CHAR),
    SOURCE_INVOICE_DISTRIBUTION_ID VARCHAR2(200 CHAR),
    SYNTHETIC_TYPE VARCHAR2(100 CHAR),
    RETRIEVAL_TEXT VARCHAR2(4000 CHAR),
    VENDOR_NAME_NORM VARCHAR2(400 CHAR),
    LINE_TYPE_NORM VARCHAR2(100 CHAR),
    IDENTITY_KEY VARCHAR2(64 CHAR),
    AMOUNT_BAND VARCHAR2(30 CHAR),
    LINE_AMOUNT NUMBER,
    UNIT_PRICE NUMBER,
    QUANTITY_INVOICED NUMBER,
    EMBEDDING_MODEL VARCHAR2(200 CHAR)
);

CREATE INDEX IDX_AG_GL_ACCOUNT_HISTORY_IDENTITY
    ON AG_GL_ACCOUNT_HISTORY_CASES (IDENTITY_KEY);

CREATE INDEX IDX_AG_GL_ACCOUNT_HISTORY_VENDOR
    ON AG_GL_ACCOUNT_HISTORY_CASES (VENDOR_NAME_NORM);

CREATE INDEX IDX_AG_GL_ACCOUNT_HISTORY_SPLIT
    ON AG_GL_ACCOUNT_HISTORY_CASES (DATASET_TYPE, IS_SYNTHETIC);

CREATE INDEX IDX_AG_GL_ACCOUNT_HISTORY_TEXT
    ON AG_GL_ACCOUNT_HISTORY_CASES (RETRIEVAL_TEXT)
    INDEXTYPE IS CTXSYS.CONTEXT;

CREATE TABLE AG_GL_VENDOR_ACCOUNT_STATS (
    VENDOR_NAME_NORM VARCHAR2(400 CHAR) NOT NULL,
    ACCOUNT_TYPE VARCHAR2(200 CHAR) NOT NULL,
    REAL_POST_COUNT NUMBER NOT NULL,
    DOMINANCE NUMBER,
    ENTROPY NUMBER,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AG_GL_VENDOR_ACCOUNT_STATS PRIMARY KEY (VENDOR_NAME_NORM, ACCOUNT_TYPE)
);

CREATE TABLE AG_GL_ACCOUNT_IDENTITY_CACHE (
    IDENTITY_KEY VARCHAR2(64 CHAR) PRIMARY KEY,
    VENDOR_NAME_NORM VARCHAR2(400 CHAR),
    LINE_DESCRIPTION_NORM VARCHAR2(4000 CHAR),
    LINE_TYPE_NORM VARCHAR2(100 CHAR),
    REAL_POST_COUNT NUMBER NOT NULL,
    ACCOUNT_TYPE VARCHAR2(200 CHAR),
    CONFLICT_FLAG VARCHAR2(1 CHAR) DEFAULT 'N' NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE AG_GL_ACCOUNT_CLASSIFICATION_OVERRIDES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IDENTITY_KEY VARCHAR2(64 CHAR),
    LINE_DESCRIPTION VARCHAR2(4000 CHAR) NOT NULL,
    VENDOR_NAME_NORM VARCHAR2(400 CHAR),
    LINE_TYPE_NORM VARCHAR2(100 CHAR),
    PREDICTED_ACCOUNT_TYPE VARCHAR2(200 CHAR),
    CORRECTED_ACCOUNT_TYPE VARCHAR2(200 CHAR),
    CONFIDENCE NUMBER,
    REASON VARCHAR2(2000 CHAR),
    SOURCE_SYSTEM VARCHAR2(100 CHAR),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE AG_GL_CLASSIFICATION_AUDIT (
    EVENT_ID RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    EVENT_TYPE VARCHAR2(100 CHAR) NOT NULL,
    EVIDENCE_HASH VARCHAR2(64 CHAR) NOT NULL,
    MODEL_VERSION VARCHAR2(200 CHAR),
    POLICY_VERSION VARCHAR2(100 CHAR) NOT NULL,
    DECISION VARCHAR2(100 CHAR) NOT NULL,
    PREDICTED_ACCOUNT_TYPE VARCHAR2(200 CHAR),
    CALIBRATED_CORRECTNESS_PROBABILITY NUMBER,
    PAYLOAD_JSON CLOB NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_AG_GL_AUDIT_PROBABILITY CHECK (
        CALIBRATED_CORRECTNESS_PROBABILITY IS NULL
        OR (CALIBRATED_CORRECTNESS_PROBABILITY >= 0 AND CALIBRATED_CORRECTNESS_PROBABILITY <= 1)
    )
);

CREATE INDEX IDX_AG_GL_CLASSIFICATION_AUDIT_CREATED
    ON AG_GL_CLASSIFICATION_AUDIT (CREATED_AT, EVENT_TYPE);

CREATE TABLE AG_GL_MODEL_REGISTRY (
    MODEL_VERSION VARCHAR2(200 CHAR) PRIMARY KEY,
    ARTIFACT_TYPE VARCHAR2(100 CHAR) NOT NULL,
    ARTIFACT_HASH VARCHAR2(64 CHAR) NOT NULL,
    DATASET_VERSION VARCHAR2(200 CHAR) NOT NULL,
    FINANCE_APPROVED VARCHAR2(1 CHAR) DEFAULT 'N' NOT NULL,
    METRICS_JSON CLOB NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_AG_GL_MODEL_APPROVAL CHECK (FINANCE_APPROVED IN ('Y', 'N'))
);
